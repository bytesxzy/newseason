/* Fetch the reference dataset (Princeton WordNet 3.1, via the npm registry's
 * wordnet-db package) into data/wordnet/, verified before anything is kept.
 *
 *   node tools/dataset-fetch.js [--registry https://registry.npmjs.org] [--force]
 *
 * Poisoning defences at this stage:
 *   - the package version is pinned; its tarball must match the registry's
 *     published sha512 `dist.integrity` or nothing is written;
 *   - the download is bounded (chunked reads, hard byte cap, timeout);
 *   - only the dictionary files the reader understands are extracted, by
 *     exact name, never paths from the archive (no path traversal);
 *   - a manifest pins the sha256 and size of every extracted file, which
 *     c4-dataset.js checks again when it opens a local copy.
 * No model, no API key: WordNet is an open lexical database.
 */
"use strict";
var https = require("https"), fs = require("fs"), path = require("path"), zlib = require("zlib"), crypto = require("crypto");
var args = process.argv.slice(2);
function arg(k, d) { var i = args.indexOf("--" + k); return i < 0 ? d : args[i + 1]; }
var REGISTRY = arg("registry", "https://registry.npmjs.org"), PKG = "wordnet-db", VERSION = "3.1.14";
var OUT = path.join(__dirname, "..", "data", "wordnet");
var WANT = /^(?:index|data)\.(?:noun|verb|adj|adv)$|^(?:noun|verb|adj|adv)\.exc$/;
var MAX_BYTES = 64 * 1024 * 1024;

function get(url, asJson) {
  return new Promise(function (resolve, reject) {
    var req = https.get(url, { timeout: 60000 }, function (res) {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) { res.resume(); return resolve(get(res.headers.location, asJson)); }
      if (res.statusCode !== 200) { res.resume(); return reject(new Error("HTTP " + res.statusCode + " for " + url)); }
      var chunks = [], n = 0;
      res.on("data", function (c) { n += c.length; if (n > MAX_BYTES) { req.destroy(new Error("download exceeds " + MAX_BYTES + " bytes")); return; } chunks.push(c); });
      res.on("end", function () { var b = Buffer.concat(chunks); resolve(asJson ? JSON.parse(b.toString("utf8")) : b); });
      res.on("error", reject);
    });
    req.on("timeout", function () { req.destroy(new Error("timeout")); });
    req.on("error", reject);
  });
}
/* ustar: 512-byte headers, name at 0 (100), size at 124 (12, octal), prefix at 345 (155) */
function untar(buf, keep) {
  var out = {}, off = 0;
  while (off + 512 <= buf.length) {
    var h = buf.slice(off, off + 512);
    if (h.every(function (x) { return x === 0; })) break;
    var name = h.slice(0, 100).toString("utf8").replace(/\0.*$/, ""), prefix = h.slice(345, 500).toString("utf8").replace(/\0.*$/, "");
    var size = parseInt(h.slice(124, 136).toString("utf8").replace(/\0.*$/, "").trim() || "0", 8), type = String.fromCharCode(h[156] || 48);
    var full = (prefix ? prefix + "/" : "") + name, base = full.split("/").pop();
    off += 512;
    if ((type === "0" || type === "\0") && keep(base) && !out[base]) out[base] = buf.slice(off, off + size);
    off += Math.ceil(size / 512) * 512;
  }
  return out;
}

/* the browser's copy of the pins: c4-dataset.js checks every file a mirror
   serves against these before a single record is used (generated here,
   never edited by hand) */
function writePins(manifest) {
  var pins = { source: manifest.source, integrity: manifest.integrity, files: manifest.files };
  fs.writeFileSync(path.join(__dirname, "..", "c4-dataset-manifest.js"),
    "/* GENERATED by tools/dataset-fetch.js from a registry-verified copy -- do not edit. */\n" +
    "(function (root) { root.C4DatasetManifest = " + JSON.stringify(pins, null, 1) + "; })(typeof window !== \"undefined\" ? window : globalThis);\n");
}
(async function () {
  if (fs.existsSync(path.join(OUT, "manifest.json")) && args.indexOf("--force") < 0) {
    writePins(JSON.parse(fs.readFileSync(path.join(OUT, "manifest.json"), "utf8")));
    console.log("dataset present: " + OUT + " (use --force to refetch); pins refreshed");
    return;
  }
  var meta = await get(REGISTRY + "/" + PKG + "/" + VERSION, true);
  var integrity = meta.dist && meta.dist.integrity;
  if (!integrity || !/^sha512-/.test(integrity)) throw new Error("registry metadata has no sha512 integrity; refusing");
  console.log("fetching " + PKG + "@" + VERSION + " (" + meta.dist.tarball + ")");
  var tgz = await get(meta.dist.tarball, false);
  var digest = "sha512-" + crypto.createHash("sha512").update(tgz).digest("base64");
  if (digest !== integrity) throw new Error("tarball integrity mismatch: refusing to use it");
  var files = untar(zlib.gunzipSync(tgz), function (b) { return WANT.test(b); });
  var names = Object.keys(files).sort();
  if (names.filter(function (n) { return /^(?:index|data)\./.test(n); }).length !== 8) throw new Error("archive is missing dictionary files: " + names.join(", "));
  fs.mkdirSync(OUT, { recursive: true });
  var manifest = { source: "npm:" + PKG + "@" + VERSION, integrity: integrity, license: "WordNet 3.1 license (Princeton University)", files: {} };
  names.forEach(function (n) {
    fs.writeFileSync(path.join(OUT, n), files[n]);
    manifest.files[n] = { bytes: files[n].length, sha256: crypto.createHash("sha256").update(files[n]).digest("hex") };
  });
  fs.writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2));
  writePins(manifest);
  console.log("verified and wrote " + names.length + " files to " + OUT);
})().catch(function (e) { console.error("dataset-fetch: " + e.message); process.exit(1); });
