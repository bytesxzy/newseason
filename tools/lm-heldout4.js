function hash(s) { var h = 5381, i; for (i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0; return h; }
function sealed(q) { return hash(q) % 3 === 0; }
var MATHY = /arith|word|algebra|units|multi/;

async function main(cases, label) {
  var LIST = cases || CASES;
  var args = process.argv.slice(2);
  function arg(k, d) { var i = args.indexOf("--" + k); return i < 0 ? d : args[i + 1]; }
  var root = path.resolve(arg("root", path.join(__dirname, "..")));
  var rt = require(path.join(root, "tools", "lm-runtime.js"));
  var peek = args.indexOf("--peek") >= 0, only = arg("cat", "");
  var rows = [], lat = [];
  for (var i = 0; i < LIST.length; i++) {
    var c = LIST[i]; if (only && c[0] !== only) continue;
    var win = rt.boot({}), a = await rt.askOnce(win, c[1], 20000), text = a.text || "";
    var hay = MATHY.test(c[0]) && c[0] !== "multi" ? firstSentence(text) : text;
    var pass = c[2].test(hay) || (MATHY.test(c[0]) && c[0] !== "units" && c[0] !== "multi" && c[2].test(text) && /^(?:\S+\s){0,14}\S+$/.test(firstSentence(text)) && false);
    var honest = !pass && SIGNAL.test(text);
    lat.push(a.latency_ms || 0);
    rows.push({ cat: c[0], q: c[1], sealed: sealed(c[1]), pass: pass, honest: honest, wrong: !pass && !honest,
                text: text.slice(0, 240), route: a.route, conf: a.raw && a.raw.lm ? a.raw.lm.confidence : undefined, ms: a.latency_ms });
  }
  lat.sort(function (x, y) { return x - y; });
  function tally(set) {
    var t = { n: set.length, pass: 0, honest: 0, wrong: 0 }, byCat = {};
    set.forEach(function (r) {
      var b = byCat[r.cat] || (byCat[r.cat] = { n: 0, pass: 0, honest: 0, wrong: 0 });
      b.n++; t[r.pass ? "pass" : r.honest ? "honest" : "wrong"]++; b[r.pass ? "pass" : r.honest ? "honest" : "wrong"]++;
    });
    t.accuracy_pct = Math.round(t.pass / Math.max(1, t.n) * 1000) / 10;
    t.by_category = byCat; return t;
  }
  var dev = rows.filter(function (r) { return !r.sealed; }), seal = rows.filter(function (r) { return r.sealed; });
  var report = { total: rows.length, all: tally(rows), dev: tally(dev), sealed: tally(seal),
                 latency: { p50: lat[lat.length >> 1], p90: lat[Math.floor(lat.length * 0.9)], max: lat[lat.length - 1] },
                 rows: rows.map(function (r) { return r.sealed && !peek ? { cat: r.cat, sealed: true, pass: r.pass, honest: r.honest } : r; }) };
  var out = arg("out", ""); if (out) fs.writeFileSync(out, JSON.stringify(report, null, 2));
  function line(n, t) { return n + ": " + t.pass + "/" + t.n + " pass (" + t.accuracy_pct + "%), honest-miss " + t.honest + ", wrong " + t.wrong; }
  console.log(line("ALL   ", report.all)); console.log(line("DEV   ", report.dev)); console.log(line("SEALED", report.sealed));
  Object.keys(report.all.by_category).forEach(function (k) { var b = report.all.by_category[k]; console.log("  " + k.padEnd(10) + b.pass + "/" + b.n + "  honest " + b.honest + "  wrong " + b.wrong); });
  console.log("latency p50 " + report.latency.p50 + " ms, p90 " + report.latency.p90 + " ms");
  if (args.indexOf("--fails") >= 0) rows.filter(function (r) { return !r.pass && (peek || !r.sealed); }).forEach(function (r) {
    console.log((r.honest ? "HONEST" : "WRONG ") + " [" + r.cat + "] " + r.q + "  =>  " + r.text.replace(/\n/g, " | ").slice(0, 170));
  });
}
